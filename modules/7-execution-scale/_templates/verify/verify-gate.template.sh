#!/usr/bin/env bash
# verify-gate - точка контролю «докази перед твердженням» (evidence before assertion).
# Запускає перевірки і ДРУКУЄ докази (вивід тестів, `git diff --stat`), щоб будь-яке
# «готово» спиралось на машинний доказ, а не на прозу. Код завершення несе вердикт:
# 0 - докази зелені, 1 - щось не зійшлось.
#
# Навіщо: автономний агент схильний написати «усе працює» без запуску чогось. Цей
# скрипт робить слід у транскрипті матеріальним - той, хто читає вивід, бачить
# реальний результат команд, а не запевнення.
#
# Як користуватись:
#   1. Скопіюй у свій репозиторій (наприклад `scripts/verify-gate.sh`), `chmod +x`.
#   2. Заміни значення двох змінних нижче під свій стек.
#   3. Запускай вручну, або з `make verify`, або як крок у CI.
#
# Плейсхолдери (заміни рядок-значення, лапки лишаються):
#   <TEST_CMD>  - команда тестів (наприклад `pytest -q` / `go test ./...` / `npm test`)
#   <TEST_DIR>  - тека тестів (наприклад `tests`)

set -uo pipefail

TEST_CMD="<TEST_CMD>"   # напр. "pytest -q" / "go test ./..." / "npm test"
TEST_DIR="<TEST_DIR>"   # напр. "tests"

FAILED=0

echo "=== verify-gate: докази перед твердженням ==="

# --- Доказ 1: тести (з повним виводом у транскрипт) ---------------------------
echo ""
echo "--- 1. Тести: $TEST_CMD ---"
if eval "$TEST_CMD"; then
  echo "Доказ: тести зелені (exit 0)."
else
  echo "Доказ: тести ЧЕРВОНІ (exit != 0)." >&2
  FAILED=1
fi

# --- Доказ 2: тести не торкалися (страхує від «полагодив тест замість коду») ---
echo ""
echo "--- 2. Чи незаймані тести: git diff --stat -- $TEST_DIR ---"
TEST_DIFF="$(git diff --stat -- "$TEST_DIR")"
if [ -z "$TEST_DIFF" ]; then
  echo "Доказ: жодної зміни в $TEST_DIR/ (тести незаймані)."
else
  echo "Доказ: $TEST_DIR/ змінено - перевір, чи не підправлено тест під реалізацію:" >&2
  echo "$TEST_DIFF" >&2
  FAILED=1
fi

# --- Доказ 3: що саме змінилось у робочому дереві ------------------------------
echo ""
echo "--- 3. Загальний diff робочого дерева: git diff --stat ---"
git diff --stat

# --- Вердикт -------------------------------------------------------------------
echo ""
if [ "$FAILED" -eq 0 ]; then
  echo "verify-gate PASS: «готово» підкріплено доказами вище."
  exit 0
fi
echo "verify-gate FAIL: докази не зійшлись - «готово» не підтверджено." >&2
exit 1
